// esbuild build config for VSCodeUEHelper extension
// Mirrors engine-link's proven esbuild setup with improvements:
//  - Production minification
//  - Source maps (external) for debugging
//  - External vscode module (provided by VS Code runtime)
//  - Watch mode for development

import * as esbuild from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const isWatch = process.argv.includes('--watch');
const isProd = process.argv.includes('--production') || (!isWatch && process.env.NODE_ENV === 'production');

/** @type {import('esbuild').BuildOptions} */
const buildOptions = {
  entryPoints: [resolve(__dirname, 'src/extension.ts')],
  bundle: true,
  outfile: resolve(__dirname, 'out/extension.js'),
  external: ['vscode', '@vscode/*'],
  format: 'cjs',
  platform: 'node',
  target: 'node18',
  sourcemap: !isProd,
  minify: isProd,
  treeShaking: true,
  logLevel: 'info',
  define: {
    'process.env.NODE_ENV': isProd ? '"production"' : '"development"',
  },
  alias: {
    '@': resolve(__dirname, 'src'),
    '@core': resolve(__dirname, 'src/core'),
    '@detection': resolve(__dirname, 'src/detection'),
    '@build': resolve(__dirname, 'src/build'),
    '@clangd': resolve(__dirname, 'src/clangd'),
    '@i18n': resolve(__dirname, 'src/i18n'),
    '@parsers': resolve(__dirname, 'src/parsers'),
    '@commands': resolve(__dirname, 'src/commands'),
    '@ui': resolve(__dirname, 'src/ui'),
    '@mcp': resolve(__dirname, 'src/mcp'),
    '@rules': resolve(__dirname, 'src/rules'),
    '@platform': resolve(__dirname, 'src/platform'),
  },
  banner: {
    js: '// VSCodeUEHelper — generated by esbuild',
  },
};

if (isWatch) {
  const ctx = await esbuild.context(buildOptions);
  await ctx.watch();
  console.log('[esbuild] watching for changes...');
} else {
  const result = await esbuild.build(buildOptions);
  if (result.errors.length > 0) {
    console.error('[esbuild] build errors:', result.errors);
    process.exit(1);
  }
  console.log('[esbuild] build complete → out/extension.js');
}